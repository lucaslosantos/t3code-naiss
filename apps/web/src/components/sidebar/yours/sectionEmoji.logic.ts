/** Catalog emoji matching every word of `query`, in catalog order. */
export function searchSectionEmoji(query: string): string[] {
  const words = query.toLowerCase().split(/\s+/u).filter(Boolean);
  return SECTION_EMOJI_CATALOG.filter((entry) =>
    words.every((word) => entry.keywords.includes(word)),
  ).map((entry) => entry.emoji);
}
